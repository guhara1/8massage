export function getRegion(regionSlug: string): Region | undefined {
  return SERVICE_AREAS[regionSlug];
}

export function getArea(regionSlug: string, areaSlug: string): Area | undefined {
  return SERVICE_AREAS[regionSlug]?.areas.find((a) => a.slug === areaSlug);
}

export function areaParams(regionSlug: string): { area: string }[] {
  return (SERVICE_AREAS[regionSlug]?.areas ?? []).map((a) => ({ area: a.slug }));
}

/** 전체 권역 경로 (sitemap 용) */
export function allAreaPaths(): string[] {
  return Object.values(SERVICE_AREAS).flatMap((r) =>
    r.areas.map((a) => `/service-area/${r.slug}/${a.slug}/`)
  );
}
